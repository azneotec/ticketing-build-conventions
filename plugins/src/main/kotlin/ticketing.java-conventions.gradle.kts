// Base conventions for every Java module in the ticketing platform.
plugins {
    java
    jacoco
    id("com.diffplug.spotless")
}

// Repositories are declared once per build in settings.gradle.kts
// (dependencyResolutionManagement), not here.

java {
    // Gradle finds (or provisions) a JDK 25 for compile/test, whatever JDK runs Gradle itself.
    toolchain { languageVersion = JavaLanguageVersion.of(TicketingVersions.JAVA) }
}

tasks.withType<JavaCompile>().configureEach {
    options.encoding = "UTF-8"
    // -parameters: keep parameter names in bytecode (Spring, Jackson rely on it).
    // -Xlint:all + -Werror: every compiler warning fails the build. Relax a lint
    // only in the module that needs it, with a comment that says why.
    options.compilerArgs.addAll(listOf("-parameters", "-Xlint:all", "-Werror"))
}

dependencies {
    testImplementation(platform("org.junit:junit-bom:${TicketingVersions.JUNIT}"))
    testImplementation("org.junit.jupiter:junit-jupiter")
    testImplementation("org.assertj:assertj-core:${TicketingVersions.ASSERTJ}")
    testRuntimeOnly("org.junit.platform:junit-platform-launcher")
}

tasks.test {
    useJUnitPlatform()
    finalizedBy(tasks.jacocoTestReport)
}

jacoco { toolVersion = TicketingVersions.JACOCO }

// Generated code (protobuf, gRPC, Avro, annotation processors) lives under build/generated.
// It is not ours to test or format, so it is excluded from coverage and from Spotless.
val generatedSourcesDir = layout.buildDirectory.dir("generated")

// Class-file paths ("io/x/Foo") of every type generated under build/generated. JaCoCo measures
// class files, which do not say where their source came from, so we read the `package` line of
// each generated .java file and exclude the matching classes (including nested Foo$Bar classes).
val generatedTypePaths: Provider<Set<String>> = provider {
    val packageLine = Regex("""^\s*package\s+([\w.]+)\s*;""", RegexOption.MULTILINE)
    generatedSourcesDir.get().asFile.walkTopDown()
        .filter { it.isFile && it.extension == "java" }
        .map { file ->
            val pkg = packageLine.find(file.readText())?.groupValues?.get(1).orEmpty()
            (if (pkg.isEmpty()) "" else pkg.replace('.', '/') + "/") + file.nameWithoutExtension
        }
        .toSet()
}

tasks.withType<JacocoReportBase>().configureEach {
    // Walk build/generated once per task run, not once per class file.
    val generated by lazy { generatedTypePaths.get() }
    classDirectories.setFrom(
        sourceSets.main.get().output.classesDirs.asFileTree.matching {
            exclude { element ->
                !element.isDirectory &&
                    element.path.removeSuffix(".class").substringBefore('$') in generated
            }
        },
    )
}

tasks.jacocoTestReport {
    dependsOn(tasks.test)
    reports {
        xml.required = true
        html.required = true
    }
}

tasks.jacocoTestCoverageVerification {
    dependsOn(tasks.test)
    violationRules {
        rule {
            limit {
                counter = "LINE"
                value = "COVEREDRATIO"
                minimum = TicketingVersions.MIN_LINE_COVERAGE.toBigDecimal()
            }
        }
    }
    // JaCoCo skips this task when no test wrote coverage data. That would let a module
    // with production code but no tests pass the gate, so run it whenever main has code
    // (no data = 0% = failure).
    // Only hand-written code counts: a module with nothing but generated code (e.g. contracts)
    // has nothing to cover.
    val handWrittenJava = sourceSets.main.get().allJava.filter {
        !it.startsWith(generatedSourcesDir.get().asFile)
    }
    setOnlyIf { !handWrittenJava.isEmpty }
}

tasks.check { dependsOn(tasks.jacocoTestCoverageVerification) }

spotless {
    java {
        targetExclude("build/generated/**")
        googleJavaFormat(TicketingVersions.GOOGLE_JAVA_FORMAT)
        removeUnusedImports()
        trimTrailingWhitespace()
        endWithNewline()
    }
}
